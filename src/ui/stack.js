// Вертикальный стек «строк» (docs/UI_LAYOUT_TODO.md, раздел 2, пункт Stack/Row):
// курсор идёт сверху вниз, шаг строки = высота ячейки + зазор. Строка сама
// расставляет свои объекты внутри ячейки через place(top) — получает верхний
// край ячейки, поэтому смешанные блоки (иконка + текст со своими смещениями)
// не ломают стек. Высота ячейки — семантическая (размер иконки или замер
// текста, как craftTextH), зазоры — из шкалы SPACE, где значение в неё
// попадает; нестандартные зазоры допустимы как именованные константы вызова.
// Возвращает нижний край стека (без хвостового зазора).
export function stackDown(rows, { top, gap = 0 }) {
    let cursor = top;
    let bottom = top;
    for (const row of rows) {
        row.place(cursor);
        bottom = cursor + row.h;
        cursor = bottom + (row.gapAfter !== undefined ? row.gapAfter : gap);
    }
    return bottom;
}
